<#
.SYNOPSIS
  Seeds clearly labeled fake development sample providers (DEV_ALPHA, DEV_BETA),
  connections with runtime-generated random secrets, provider coverage, and a sample
  customer commercial profile through the service layer.
  Refuses to run unless APP_ENV=development.
.PARAMETER Cleanup
  Removes all fake development sample providers, connections, coverage rows, customer profiles, and sender IDs.
#>
[CmdletBinding()]
param(
    [switch]$Cleanup
)

. "$PSScriptRoot\_common.ps1"
Initialize-Script

$appEnv = Get-Setting 'APP_ENV'
if ($appEnv -ne 'development') {
    Write-Error "REFUSED: APP_ENV must be 'development'. This provider sample seed script is strictly prohibited from running in staging or production environments."
    exit 1
}

Assert-Command 'go' 'Install Go 1.22+.'

$argsList = @('run', './cmd/seedproviderssample')
if ($Cleanup) {
    $argsList += @('-cleanup')
}

Push-Location -LiteralPath (Join-Path $script:RepoRoot 'backend')
try {
    Write-Host "Running provider sample seed tool (Cleanup: $Cleanup)..." -ForegroundColor Cyan
    & go @argsList
    if ($LASTEXITCODE -ne 0) {
        exit $LASTEXITCODE
    }
} finally {
    Pop-Location
}
